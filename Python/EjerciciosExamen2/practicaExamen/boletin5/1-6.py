import random

def primitiva():
    # random.sample selecciona k elementos sin repetición de un rango (o lista)
    numeros = random.sample(range(1, 50), 6)  # range(1,50) genera 1..49 al parece random si genera el ultimo num no como range
    numeros.sort()  # opcional: ordenar para presentación
    return numeros
print("Números de la primitiva:", primitiva())

